// Generates db/init/03-seed-players.sql from data/players.json
// Usage: node scripts/generate-seed.js   (re-run whenever players.json changes)
const fs = require('fs');
const path = require('path');

const players = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', 'players.json'), 'utf8'));
// Dollar-quoted JSON: no manual escaping needed, as long as the tag never appears in the data.
if (JSON.stringify(players).includes('$players$')) throw new Error('Data contains the quote tag');

const sql = `-- GENERATED by scripts/generate-seed.js from data/players.json - do not edit by hand.
INSERT INTO players (
  id, name, common_name, rating, position, alt_positions, card_type, club, league, nation,
  nation_code, flag, gender, age, height, weight, foot, skill_moves, weak_foot,
  work_rate_att, work_rate_def, price_estimate, avatar_color, card_accent,
  pac, sho, pas, dri, def, phy, detailed_stats, play_styles_plus, play_styles, bio
)
SELECT
  p->>'id', p->>'name', p->>'commonName', (p->>'rating')::smallint, p->>'position',
  ARRAY(SELECT jsonb_array_elements_text(COALESCE(p->'altPositions', '[]'))),
  p->>'cardType', p->>'club', p->>'league', p->>'nation', p->>'nationCode', p->>'flag',
  p->>'gender', (p->>'age')::smallint, (p->>'height')::smallint, (p->>'weight')::smallint,
  p->>'foot', (p->>'skillMoves')::smallint, (p->>'weakFoot')::smallint,
  p->>'workRateAtt', p->>'workRateDef', COALESCE((p->>'priceEstimate')::int, 0),
  p->>'avatarColor', p->>'cardAccent',
  (p#>>'{stats,pac}')::smallint, (p#>>'{stats,sho}')::smallint, (p#>>'{stats,pas}')::smallint,
  (p#>>'{stats,dri}')::smallint, (p#>>'{stats,def}')::smallint, (p#>>'{stats,phy}')::smallint,
  COALESCE(p->'detailedStats', '{}'),
  ARRAY(SELECT jsonb_array_elements_text(COALESCE(p->'playStylesPlus', '[]'))),
  ARRAY(SELECT jsonb_array_elements_text(COALESCE(p->'playStyles', '[]'))),
  p->>'bio'
FROM jsonb_array_elements($players$${JSON.stringify(players)}$players$::jsonb) AS p;
`;
fs.writeFileSync(path.join(__dirname, '..', 'db', 'init', '03-seed-players.sql'), sql);
console.log(`Wrote seed for ${players.length} players`);
